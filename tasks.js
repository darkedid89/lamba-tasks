function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
}

function chip(text, className) {
  return el('span', 'chip' + (className ? ' ' + className : ''), text);
}

function copyButton(source) {
  const button = el('button', 'copy', 'Копировать');
  button.type = 'button';
  button.addEventListener('click', () => {
    const text = source.innerText;
    const done = () => {
      button.textContent = 'Скопировано';
      button.classList.add('done');
      setTimeout(() => {
        button.textContent = 'Копировать';
        button.classList.remove('done');
      }, 1500);
    };
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(done);
    } else {
      const area = document.createElement('textarea');
      area.value = text;
      area.style.position = 'fixed';
      area.style.opacity = '0';
      document.body.appendChild(area);
      area.select();
      document.execCommand('copy');
      document.body.removeChild(area);
      done();
    }
  });
  return button;
}

// Placeholders in <angle brackets> are highlighted: they are what Roman replaces.
function promptBlock(text) {
  const wrap = el('div', 'cmd');
  const pre = el('pre');
  const code = el('code');
  text.split(/(<[^<>]+>)/).forEach((part) => {
    if (!part) return;
    code.appendChild(/^<[^<>]+>$/.test(part) ? el('span', 'fill', part) : document.createTextNode(part));
  });
  pre.appendChild(code);
  wrap.appendChild(pre);
  wrap.appendChild(copyButton(code));
  return wrap;
}

function listBox(title, items, ordered, className) {
  const box = el('section', 'box' + (className ? ' ' + className : ''));
  box.appendChild(el('h2', null, title));
  const list = el(ordered ? 'ol' : 'ul');
  items.forEach((item) => list.appendChild(el('li', null, item)));
  box.appendChild(list);
  return box;
}

function textBox(title, text, className) {
  const box = el('section', 'box' + (className ? ' ' + className : ''));
  box.appendChild(el('h2', null, title));
  box.appendChild(el('p', null, text));
  return box;
}

function taskLink(task) {
  return 'task.html?id=' + encodeURIComponent(task.id);
}

function renderIndex(root) {
  root.appendChild(el('h1', null, 'Задачи по Lamba'));
  const lead = el('p', 'lead');
  lead.append('Сверху — самое важное. Нажми на задачу, чтобы открыть шаги и готовый промпт для Claude. Перед началом прочитай ');
  const guide = el('a', null, '«Как работать»');
  guide.href = 'guide.html';
  lead.append(guide, '.');
  root.appendChild(lead);

  Object.entries(PRIORITIES).forEach(([key, group]) => {
    const tasks = TASKS.filter((task) => task.priority === key);
    if (!tasks.length) return;
    const heading = el('h2', 'group', group.label);
    heading.appendChild(el('span', 'group-note', group.note));
    root.appendChild(heading);
    tasks.forEach((task) => {
      const card = el('a', 'card ' + key);
      card.href = taskLink(task);
      const title = el('div', 'card-title');
      title.appendChild(el('span', 'card-num', String(TASKS.indexOf(task) + 1)));
      title.appendChild(el('span', null, task.title));
      card.appendChild(title);
      card.appendChild(el('p', 'card-summary', task.summary));
      const chips = el('div', 'chips');
      chips.appendChild(chip(task.type));
      if (task.need) chips.appendChild(chip('нужно от Игоря', 'need'));
      card.appendChild(chips);
      root.appendChild(card);
    });
  });

  const extra = el('h2', 'group', 'Ещё');
  root.appendChild(extra);
  root.appendChild(listBox('Ждём от Игоря', WAITING, false, 'need'));
  root.appendChild(listBox('Уточнить', UNCLEAR, false, 'warn'));
  root.appendChild(el('footer', null, 'Обновлено ' + UPDATED + '.'));
}

function renderTask(root) {
  const id = new URLSearchParams(location.search).get('id');
  const index = TASKS.findIndex((task) => task.id === id);
  if (index < 0) {
    root.appendChild(el('h1', null, 'Задача не найдена'));
    const back = el('a', null, '← Ко всем задачам');
    back.href = 'index.html';
    root.appendChild(back);
    return;
  }
  const task = TASKS[index];
  const number = index + 1;
  document.title = number + '. ' + task.title + ' — задачи Lamba';

  const head = el('div', 'task-head');
  const chips = el('div', 'chips');
  chips.appendChild(chip(PRIORITIES[task.priority].label, task.priority));
  chips.appendChild(chip(task.type));
  head.appendChild(chips);
  head.appendChild(el('h1', null, number + '. ' + task.title));
  head.appendChild(el('p', 'lead', task.summary));
  root.appendChild(head);

  if (task.need) root.appendChild(textBox('Нужно от Игоря', task.need, 'need'));
  root.appendChild(textBox('Зачем', task.goal));
  root.appendChild(listBox('Как делать', task.steps, true));
  root.appendChild(textBox('Готово, когда', task.done));
  if (task.prompt) {
    const box = el('section', 'box');
    box.appendChild(el('h2', null, 'Промпт для Claude'));
    box.appendChild(promptBlock(task.prompt));
    box.appendChild(el('p', 'hint', 'Скопируй, замени жёлтое своими данными. Новая сессия (Local) → режим Plan → Fable 5.2. Дальше — как в «Как работать».'));
    root.appendChild(box);
  }
  if (task.limits) root.appendChild(listBox('Ограничения', task.limits, false, 'warn'));

  const pager = el('div', 'pager');
  if (index > 0) {
    const prev = el('a', 'prev', '← ' + index + '. ' + TASKS[index - 1].title);
    prev.href = taskLink(TASKS[index - 1]);
    pager.appendChild(prev);
  }
  if (index < TASKS.length - 1) {
    const next = el('a', 'next', number + 1 + '. ' + TASKS[index + 1].title + ' →');
    next.href = taskLink(TASKS[index + 1]);
    pager.appendChild(next);
  }
  root.appendChild(pager);
}

document.addEventListener('DOMContentLoaded', () => {
  const root = document.getElementById('app');
  if (root.dataset.page === 'task') renderTask(root);
  else renderIndex(root);
});
